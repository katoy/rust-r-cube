/// 指定されたMoveに対する逆引きマッピング (destination_index -> source_index)
pub fn get_source_index(mv: Move, dst_idx: usize) -> usize {
    let all_moves = Move::all_moves();
    let move_idx = all_moves.iter().position(|&m| m == mv).unwrap_or(0);

    for &(src, dst) in &MOVE_MAPPING_TABLE[move_idx] {
        if dst == dst_idx && src != 99 {
            return src;
        }
    }
    dst_idx
}

/// 指定されたMoveに対する順引きマッピング (source_index -> destination_index)
pub fn get_destination_index(mv: Move, src_idx: usize) -> usize {
    let all_moves = Move::all_moves();
    let move_idx = all_moves.iter().position(|&m| m == mv).unwrap_or(0);

    for &(src, dst) in &MOVE_MAPPING_TABLE[move_idx] {
        if src == src_idx {
            return dst;
        }
    }
    src_idx
}

/// 指定されたMoveとインデックスに対する論理的な向きの変更量 (0-3)
pub fn get_oris_delta(mv: Move, src_idx: usize) -> u8 {
    use glam::Mat4;
    let (axis, angle) = mv.geometric_params();
    let rot = Mat4::from_axis_angle(axis, angle);

    let src_face_idx = src_idx / 9;
    let initial_normal = match src_face_idx {
        0 => glam::Vec3::Y,
        1 => -glam::Vec3::Y,
        2 => -glam::Vec3::X,
        3 => glam::Vec3::X,
        4 => glam::Vec3::Z,
        5 => -glam::Vec3::Z,
        _ => glam::Vec3::Y,
    };

    let current_normal = rot.transform_vector3(initial_normal);
    crate::cube::piece::calculate_orientation_with_rot(initial_normal, current_normal, rot)
}
